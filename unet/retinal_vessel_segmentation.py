def validate_model(model, loader, criterion, device):

    model.eval()

    total_loss = 0.0

    TP = 0
    TN = 0
    FP = 0
    FN = 0

    with torch.no_grad():

        for images, masks, fov_masks in loader:

            images = images.to(device)
            masks = masks.to(device)
            fov_masks = fov_masks.to(device)

            logits = model(images)

            loss = criterion(logits, masks, fov_masks)

            total_loss += loss.item()

            probabilities = torch.sigmoid(logits)
            predictions = (probabilities >= 0.5)

            valid = fov_masks.bool()
            targets = masks.bool()

            TP += ((predictions == 1) & targets & valid).sum().item()
            TN += ((predictions == 0) & (~targets) & valid).sum().item()
            FP += ((predictions == 1) & (~targets) & valid).sum().item()
            FN += ((predictions == 0) & targets & valid).sum().item()

    epsilon = 1e-7

    dice = (2 * TP) / (2 * TP + FP + FN + epsilon)

    iou = TP / (TP + FP + FN + epsilon)

    sensitivity = TP / (TP + FN + epsilon)

    specificity = TN / (TN + FP + epsilon)

    avg_loss = total_loss / len(loader)

    return {
        "loss": avg_loss,
        "dice": dice,
        "iou": iou,
        "sensitivity": sensitivity,
        "specificity": specificity
    }

