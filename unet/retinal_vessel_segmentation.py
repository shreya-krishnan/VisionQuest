class RetinalDataset(Dataset):

    def __init__(self, data_pairs):
        self.data_pairs = data_pairs

    def __len__(self):
        return len(self.data_pairs)

    def __getitem__(self, index):

        sample = self.data_pairs[index]

        # Load RGB image
        image = cv2.imread(sample["image"])
        image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)

        # Load ground truth
        manual = cv2.imread(
            sample["manual"],
            cv2.IMREAD_GRAYSCALE
        )

        # Load FOV mask
        fov = cv2.imread(
            sample["fov"],
            cv2.IMREAD_GRAYSCALE
        )

        # Normalize image
        image = image.astype(np.float32) / 255.0

        # Convert ground truth to binary
        manual = (manual > 127).astype(np.float32)

        # Convert FOV to binary
        fov = (fov > 127).astype(np.float32)

        # HWC -> CHW
        image = np.transpose(image, (2, 0, 1))

        # Add channel dimension to masks
        manual = np.expand_dims(manual, axis=0)
        fov = np.expand_dims(fov, axis=0)

        # Convert to PyTorch tensors
        image = torch.tensor(image, dtype=torch.float32)
        manual = torch.tensor(manual, dtype=torch.float32)
        fov = torch.tensor(fov, dtype=torch.float32)

        return image, manual, fov

