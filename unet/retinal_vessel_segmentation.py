"""# **Loss Functions and Evaluation Metrics**"""

class BCEDiceLoss(nn.Module):

    def __init__(self):
        super().__init__()

        self.bce = nn.BCEWithLogitsLoss(reduction="none")

    def forward(self, logits, targets, fov_mask):

        # Calculate pixel-wise BCE
        bce_map = self.bce(logits, targets)

        # Ignore pixels outside FOV
        bce_loss = (
            bce_map * fov_mask
        ).sum() / fov_mask.sum().clamp_min(1.0)

        # Convert logits to probabilities
        probabilities = torch.sigmoid(logits)

        # Calculate masked Dice
        intersection = (
            probabilities * targets * fov_mask
        ).sum()

        denominator = (
            probabilities * fov_mask
        ).sum() + (
            targets * fov_mask
        ).sum()

        dice_score = (
            2.0 * intersection + 1e-7
        ) / (
            denominator + 1e-7
        )

        dice_loss = 1.0 - dice_score

        # Combined loss
        total_loss = bce_loss + dice_loss

        return total_loss

def calculate_metrics(logits, targets, fov_mask, threshold=0.5):

    # Convert logits into probabilities
    probabilities = torch.sigmoid(logits)

    # Convert probabilities to binary predictions
    predictions = (probabilities >= threshold).float()

    # Restrict evaluation to valid FOV pixels
    valid = fov_mask.bool()

    predictions = predictions[valid]
    targets = targets[valid].bool()

    # Calculate confusion matrix values
    TP = ((predictions == 1) & targets).sum().float()
    TN = ((predictions == 0) & (~targets)).sum().float()
    FP = ((predictions == 1) & (~targets)).sum().float()
    FN = ((predictions == 0) & targets).sum().float()

    epsilon = 1e-7

    # Calculate metrics
    dice = (2 * TP) / (2 * TP + FP + FN + epsilon)

    iou = TP / (TP + FP + FN + epsilon)

    sensitivity = TP / (TP + FN + epsilon)

    specificity = TN / (TN + FP + epsilon)

    return {
        "Dice": dice.item(),
        "IoU": iou.item(),
        "Sensitivity": sensitivity.item(),
        "Specificity": specificity.item()
    }

